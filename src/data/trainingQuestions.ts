const template = (items: string[]) => items;

const unique = (items: string[]): string[] =>
  Array.from(new Set(items.map((item) => item.trim()).filter(Boolean)));

const firstSentences = (text: string, count: number): string => {
  const sentences = text
    .split("。")
    .map((sentence) => sentence.trim())
    .filter(Boolean)
    .slice(0, count);
  return sentences.length ? `${sentences.join("。")}。` : text;
};

const deriveKeywords = (question: TrainingQuestionSeed): string[] => {
  const topicParts = question.topic
    .split(/[と・、/／]/)
    .map((item) => item.trim())
    .filter((item) => item.length >= 2);
  const learnerFacingTags = question.tags.filter(
    (tag) =>
      tag.length >= 2 &&
      !["term", "case", "kpi", "manufacturing-ai"].includes(tag) &&
      (/^[A-Z0-9/-]+$/.test(tag) || /[\u3040-\u30ff\u3400-\u9fff]/.test(tag)),
  );
  return unique([
    ...topicParts,
    ...learnerFacingTags,
    ...(question.relatedKpis ?? []).slice(0, 2),
  ]).slice(0, 7);
};

const buildModelAnswer30Sec = (question: TrainingQuestionSeed): string => {
  const kpiNote = question.relatedKpis?.length
    ? `見るKPIは${question.relatedKpis.slice(0, 2).join("、")}です。`
    : "";
  return `${firstSentences(question.expectedAnswer, 2)}${kpiNote}`;
};

const buildModelAnswer90Sec = (question: TrainingQuestionSeed): string => {
  const points = question.keyPoints.length
    ? `答える時は、${question.keyPoints.slice(0, 4).join("、")}を押さえます。`
    : "";
  const boundary = question.responsibilityBoundary
    ? `責任分界としては、${question.responsibilityBoundary}`
    : "";
  const caution = question.ngPatterns.length
    ? `避けるべきなのは、${question.ngPatterns.slice(0, 2).join("、")}です。`
    : "";
  return unique([question.expectedAnswer, points, boundary, caution]).join("");
};

