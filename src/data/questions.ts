import type { Domain, Question } from "../types";

type Difficulty = 1 | 2 | 3;

const options = (items: string[]) =>
  items.map((text, index) => ({ id: String.fromCharCode(97 + index), text }));

const mc = (
  id: string,
  domain: Domain,
  category: string,
  difficulty: Difficulty,
  prompt: string,
  correct: string,
  distractors: string[],
  explanation: string,
  relatedConceptIds: string[],
  cautionExpression?: string,
): Question => ({
  id,
  type: "multiple-choice",
  domain,
  category,
  difficulty,
  prompt,
  options: options([correct, ...distractors]),
  correctOptionIds: ["a"],
  explanation,
  relatedConceptIds,
  cautionExpression,
});

const tf = (
  id: string,
  domain: Domain,
  category: string,
  difficulty: Difficulty,
  prompt: string,
  answer: boolean,
  explanation: string,
  relatedConceptIds: string[],
  cautionExpression?: string,
): Question => ({
  id,
  type: "true-false",
  domain,
  category,
  difficulty,
  prompt,
  options: [
    { id: "true", text: "正しい" },
    { id: "false", text: "違う" },
  ],
  correctOptionIds: [answer ? "true" : "false"],
  explanation,
  relatedConceptIds,
  cautionExpression,
});

const caution = (
  id: string,
  domain: Domain,
  category: string,
  difficulty: Difficulty,
  prompt: string,
  badExpression: string,
  safeOptions: string[],
  explanation: string,
  relatedConceptIds: string[],
): Question => ({
  id,
  type: "caution",
  domain,
  category,
  difficulty,
  prompt,
  options: options([badExpression, ...safeOptions]),
  correctOptionIds: ["a"],
  explanation,
  relatedConceptIds,
  cautionExpression: badExpression,
});

const scenario = (
  id: string,
  domain: Domain,
  category: string,
  difficulty: Difficulty,
  prompt: string,
  bestResponse: string,
  weakResponses: string[],
  explanation: string,
  relatedConceptIds: string[],
  cautionExpression: string,
): Question => ({
  id,
  type: "scenario",
  domain,
  category,
  difficulty,
  prompt,
  options: options([bestResponse, ...weakResponses]),
  correctOptionIds: ["a"],
  explanation,
  relatedConceptIds,
  cautionExpression,
});

